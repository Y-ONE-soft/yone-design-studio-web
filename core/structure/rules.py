"""단락 종류 판정 룰 테이블 (docs/taxonomy/09_워크북_단락종류.md 구현).

룰은 전부 이 파일의 데이터 테이블에 있다 — 새 표기 대응 = 테이블에 항목 추가.
판정 파이프라인(우선순위·컨텍스트 로직)은 paragraph_kind.py.

원칙 (09 문서): 위치 + 마커 + 컨텍스트 + 언어 + 길이의 조합으로 판정하고,
단어 리터럴은 시그니처의 한 층일 뿐 단독 판정 근거가 아니다.
"""
import re

# ── GH: 그룹 헤더 (출력 제거 대상 — 최우선으로 빼냄) ─────────────────────────
GH_PATTERNS = [
    re.compile(r'^\[(?:Gateway|gateway|\d+)\]$'),          # [Gateway] / [3]
    re.compile(r'^\[\s*유형\s*\d+\s*\]'),                   # [유형 12]
    re.compile(r'^\[\s*\d+\s*(?:과|번|강)\s*\]$'),          # [3과] / [20번] / [5강]
    re.compile(r'^\d{4}\s*년?\s*수능특강'),                  # 2027수능특강 ...
    re.compile(r'^Exercises\s*$'),                          # 수능특강 발문 뒤 단독 줄
    re.compile(r'^CH\d+\s*\d+\s*강'),                       # CH5 17강 변형문제
    re.compile(r'^리딩파워'),                                 # 리딩파워 유형편 [기본]
    re.compile(r'^본\s*자료는\s.*(?:출판권|제작)'),           # 저작권 고지 줄
    re.compile(r'^.{0,20}지문\s*변형\s*[–\-—]\s*\d+\s*차\s*$'),      # "고 난이도 지문 변형 – 1차"
]
# 유형 부제 "(빈칸, 함축의미)" — 한글 토큰 2개+ 괄호 단독 라인
GH_SUBTITLE = re.compile(r'^\(\s*[가-힣][가-힣\s,/&·]*[가-힣]\s*\)$')
GH_SUBTITLE_MIN_TOKENS = 2

# ── A: 정답/해설 ─────────────────────────────────────────────────────────────
CIRCLED = '①②③④⑤'
A_PATTERNS = [
    re.compile(r'^\s*[①②③④⑤](?:\s*,\s*[①②③④⑤])*\s*$'),        # 정답 단독
    re.compile(r'^\s*[①②③④⑤]\s*(?:,\s*[①②③④⑤]\s*)*:\s*.+'),   # 정답: 해설
    re.compile(r'^\s*(?:\[?\s*정답\s*\]?|【\s*정답\s*】|<\s*정답\s*>'
               r'|정답\s*(?:및|과)?\s*해설|빠른\s*정답\s*찾기|정답지|해설)\s*$'),
]

# ── Box / Cond: 박스 마커 (정규화: 꺾쇠/대괄호/단독 모두 수용) ────────────────
BOX_MARKERS = {
    # Cond를 먼저 검사 (아래 Box의 일반 꺾쇠 마커가 <조건>을 삼키지 않도록)
    "Cond": re.compile(r'^\s*(?:<\s*조\s*건\s*>|\[\s*조\s*건\s*\]|조건)\s*$'),
    # <보기> + 일반 꺾쇠 마커 (<요지> <요약> <보기 A> 등 — 정답류는 A가 선점)
    "Box": re.compile(r'^\s*(?:<\s*[가-힣]{1,4}(?:\s*[A-Z0-9])?\s*>|\[\s*보기\s*\]|보기)\s*$'),
}
# 마커 뒤 propagation 종료/지속 신호
COND_ITEM_START = re.compile(r'^\s*(?:[•·\-*]|[①②③④⑤])')
BOX_WORDLIST = re.compile(r'/|(?:,[^,]*){3,}')   # 슬래시 또는 쉼표 3개+ 나열

# ── Q: 발문 (분류기 실패 시 구조 폴백) ───────────────────────────────────────
Q_FALLBACK_PATTERNS = [
    re.compile(r'^\d+\.\s.*(?:\?|시오\.?|것은\??|것을)\s*$'),   # "3. ... 것은?"
    re.compile(r'^서술형\s*\d+\s*[.)]'),                        # "서술형1."
    re.compile(r'(?:시오|것은|곳은|것을|까)\s*[?.!]?\s*$'),       # 한글 종결어미 (앞 공백 허용)
]
# 폴백 종결어미 단독은 오탐 위험 → 발문 시작 신호와 AND 결합
Q_START_HINT = re.compile(r'^(?:\d+\s*[.)]|서술형|다음|위\s*글|글의|밑줄|주어진)')
Q_INTRO_FALLBACK = [
    re.compile(r'^(?:※\s*)?다음\s*글을\s*읽고\s*,?\s*물음에\s*답하시오'),
    re.compile(r'^\[\d+\s*~\s*\d+\]\s*다음\s*글'),
]

# ── C: 선지 ──────────────────────────────────────────────────────────────────
C_START = re.compile(r'^[①②③④⑤]')
C_AB_HEADER = re.compile(r'^\(A\)(?:\s{2,}|\t)')                # (A)  (B)  (C) 헤더

# ── P: 영어 본문 ─────────────────────────────────────────────────────────────
P_MIN_LEN = 80
P_ENGLISH_START = re.compile(r'^[A-Za-z"\'“‘(\[]')
HANGUL = re.compile(r'[가-힣]')
# 순서배열 (A)(B)(C) 단락 시작
P_ORDER_LABEL = re.compile(r'^\((?:A|B|C)\)\s+\S')

# P-CONTEXT를 유발하는 발문 leaf 코드 (문장삽입/순서배열 계열)
P_CONTEXT_Q_CODES = re.compile(r'^OBJ-FLW-(?:INSERT|ORDER)')

# ── K: 한글 해석 ─────────────────────────────────────────────────────────────
K_MIN_RATIO = 0.7
K_MIN_LEN = 30

# ── Word: 영단어 박스 ────────────────────────────────────────────────────────
WORD_MAX_LEN = 100
WORD_MARKER = re.compile(r'\*')
WORD_DEF = re.compile(r'^[a-zA-Z][a-zA-Z \-]*\s*[:：]')

# ── 발문 꼬리 태그: 분류 전에 제거 후 판정 ([ep1] [pr1] [3점] 등) ────────────
Q_TRAILING_TAG = re.compile(r'\s*\[(?:[A-Za-z]+\d*|\d+\s*점)\]\s*$')

# ── Sym: 구조 기호 단독 라인 (요약 화살표 등) ────────────────────────────────
SYM_LINE = re.compile(r'^[↓→↑↔⇒▶►⬇⬆⬅➡]+$')

# ── Ans: 서술형 답 작성란 ────────────────────────────────────────────────────
ANS_PATTERNS = [
    re.compile(r'^[^_]{0,15}_{3,}\s*_*\s*$'),                  # "(A): ______"
    re.compile(r'^[\s\d()（）\u00a0:：→.\-]*(?:_{3,}[\s\u00a0→]*)+$'),  # "(1) ___ → ___"
    re.compile(r'^\([\s\u00a0]*\)[\s\u00a0]*→?\s*$'),        # "(      ) →"
    re.compile(r'^<[가-힣\s]+>[\s\u00a0]*<[가-힣\s]+>$'),       # "<기호>  <올바른 형태>"
]

# ── P 보조: 짧은 영어 완결문 (주어진 문장 등 — 종결부호 필수) ─────────────────
P_SHORT_MIN_LEN = 30
P_SENTENCE_END = re.compile(r'[.!?]["’”\')\]]?\s*$')

# ── Box 마커 + 내용 한 줄 ("<보기> with / a way / ...") ──────────────────────
BOX_INLINE = re.compile(r'^\s*<\s*보\s*기\s*[A-Z0-9]?\s*>\s*\S')

# ── P 선행 노이즈: ".19 Dear Residents..." 류 숫자 마커 잔재 ─────────────────
P_LEADING_NOISE = re.compile(r'^[.\s]*\d+\s+(?=[A-Z"“])')

# ── Q 꼬리 괄호 주석: "...작성하시오. (필요시 어형 변화 가능)" ────────────────
Q_TRAILING_PAREN = re.compile(r'\s*\([^)]{0,60}\)\s*$')

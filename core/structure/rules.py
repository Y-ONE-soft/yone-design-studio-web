# 꼬리 단서는 괄호만이 아니라 **꺾쇠**로도 온다 — `…배열하시오. <한 단어는
# 추가할 것>` (명일2 실증: 이 발문이 UNKNOWN 으로 남아 서술형 하나가 사라졌다).
# 줄 **끝**의 꺾쇠만 본다(줄 머리 `<보기>` 는 상자 마커라 건드리면 안 된다).
Q_TRAILING_ANGLE = re.compile(r'\s*[<〈][^<>〈〉]{0,60}[>〉]\s*$')

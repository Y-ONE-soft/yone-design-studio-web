# ── 괄호 이형 정규화 (W50) ───────────────────────────────────────────────────
# 원고는 마커 괄호를 ASCII <>·[] 외에 CJK 꺾쇠 〈〉(U+3008/9)·《》·전각
# ＜＞·【】 등으로 쓴다 (2026-08-11 de909e4d 실증: 〈보기〉/〈요약문〉이
# 전부 UNKNOWN → 기본 지문 스타일). 마커 정규식마다 문자 클래스를 늘리는

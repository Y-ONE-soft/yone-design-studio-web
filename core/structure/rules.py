# 제목 〈…〉 등)는 건드리지 않는다. 문자 하나 차이로 리터럴 매칭이
# 깨지는 반복(dingbat ➀→① 전례)의 마커판 봉합.
_BRACKET_TRANS = str.maketrans({
    "〈": "<", "〉": ">", "《": "<", "》": ">",
    "＜": "<", "＞": ">", "﹤": "<", "﹥": ">",
    "【": "[", "】": "]", "〔": "[", "〕": "]",
})


def norm_brackets(s):
    """마커 인식용 괄호 이형 정규화 — 표기 자체는 보존하고 판정에만 사용."""
    return (s or "").translate(_BRACKET_TRANS)


